ModelId = Literal["flow_matching_2d_cond", "diffusion_2d_cond", "cgan_cnn_2d"]
CheckpointSource = Literal["local", "auto", "hf"]


@dataclasses.dataclass
class Args:
    """Command-line arguments for a dedicated generation throughput benchmark."""

    model_id: ModelId = "cgan_cnn_2d"
    """Model family to benchmark."""
    problem_id: str = "beams2d"
    """EngiBench problem identifier."""
    seed: int = 1
    """Seed used for condition sampling and generation setup."""
    n_samples: int = 50
    """Batch size generated by each timed call."""
    warmup_repeats: int = 10
    """Untimed warm-up generations before measurement."""
    timed_repeats: int = 100
    """Number of synchronized timed generations."""
    output_csv: str = "generation_timing_{model_id}_{problem_id}_seed{seed}.csv"
    """Output CSV path template; may include {model_id}, {problem_id}, and {seed}."""
    append_output: bool = True
    """Append to an existing CSV. Use --no-append-output to overwrite."""
    checkpoint_path: str | None = None
    """Exact checkpoint file to benchmark. Preferred when provided."""
    checkpoint_dir: str | None = None
    """Directory containing validation_metrics.json and top-k checkpoints."""
    checkpoint_source: CheckpointSource = "local"
    """Source for top-k checkpoints when checkpoint_dir is used."""
    checkpoint_package_label: str | None = None
    """Optional HF package label for restored top-k checkpoint bundles."""
    top_k: int = 5
    """Number of validation-MMD top-k entries to inspect when selecting from checkpoint_dir."""
    wandb_project: str = "engiopt"
    """W&B project used only for HF/W&B fallback checkpoint resolution metadata."""
    wandb_entity: str | None = None
    """W&B entity used only for HF/W&B fallback checkpoint resolution metadata."""
    hf_entity: str = ""
    """HF org/user where checkpoint packages are stored. Empty infers the token username."""
    hf_repo_prefix: str = "engiopt"
    """HF repo prefix used for model-family repositories."""
    device: str = "auto"
    """Device selection: auto, cuda, mps, or cpu."""
    flow_method: str = "euler"
    """Flow-matching integration method."""
    flow_integration_steps: int | None = None
    """Optional override for flow-matching integration steps."""
    atol: float = 1e-3
    """Absolute tolerance for adaptive flow-matching solvers."""
    rtol: float = 1e-3
    """Relative tolerance for adaptive flow-matching solvers."""


def select_device(device_arg: str) -> th.device:
    """Return the requested torch device or the best available device."""
    if device_arg != "auto":
        if device_arg == "cuda" and not th.cuda.is_available():
            raise ValueError("CUDA device requested but not available")
        if device_arg == "mps" and not th.backends.mps.is_available():
            raise ValueError("MPS device requested but not available")
        return th.device(device_arg)
    if th.cuda.is_available():
        return th.device("cuda")
    if th.backends.mps.is_available():
        return th.device("mps")
    return th.device("cpu")


def gpu_name(device: th.device) -> str:
    """Return a human-readable GPU/device name for benchmark metadata."""
    if device.type == "cuda":
        return th.cuda.get_device_name(device)
    if device.type == "mps":
        return "Apple MPS"
    return platform.processor() or "cpu"


def resolve_checkpoint(args: Args) -> tuple[Path, str, int | None, float | None]:
    """Resolve the checkpoint path and record how it was selected."""
    if args.checkpoint_path is not None:
        return Path(args.checkpoint_path), "explicit_checkpoint_path", None, None

    if args.checkpoint_dir is None:
        raise ValueError("Either --checkpoint-path or --checkpoint-dir must be provided")

    checkpoint_dir, source = restore_topk_checkpoint_dir(
        model_id=args.model_id,
        problem_id=args.problem_id,
        seed=args.seed,
        checkpoint_source=args.checkpoint_source,
        checkpoint_dir=args.checkpoint_dir,
        hf_entity=args.hf_entity,
        hf_repo_prefix=args.hf_repo_prefix,
        wandb_project=args.wandb_project,
        wandb_entity=args.wandb_entity,
        package_label=args.checkpoint_package_label,
    )

    if args.model_id == "flow_matching_2d_cond":
        from engiopt.flow_matching_2d_cond.evaluate_flow_matching_2d_cond import (
            load_top_k_candidates as load_flow_top_k_candidates,
        )

        candidates = load_flow_top_k_candidates(checkpoint_dir, args.top_k)
    elif args.model_id == "diffusion_2d_cond":
        candidates = load_diffusion_top_k_candidates(checkpoint_dir, args.top_k)
    else:
        candidates = load_cgan_top_k_candidates(checkpoint_dir, args.top_k)
    selected = candidates[0]
    return Path(selected["checkpoint_path"]), source, int(selected["epoch"]), float(selected["metric_value"])


def load_cgan_generation_fn(
    *,
    checkpoint_path: Path,
    problem: Any,
    conditions_tensor: th.Tensor,
    device: th.device,
    seed: int,
) -> tuple[Callable[[], th.Tensor], dict[str, Any]]:
    """Load cGAN and return a callable that performs one batched generation."""
    checkpoint = th.load(str(checkpoint_path), map_location=device)
    run_config: dict[str, Any] = dict(checkpoint.get("args", {}))
    latent_dim = int(run_config["latent_dim"])
    model = Generator(
        latent_dim=latent_dim,
        n_conds=len(problem.conditions_keys),
        design_shape=problem.design_space.shape,
        generator_output_activation=run_config.get("generator_output_activation", "tanh"),
    ).to(device)
    model.load_state_dict(checkpoint["generator"])
    model.eval()

    generator = th.Generator(device=device)
    generator.manual_seed(seed)
    z = th.randn((conditions_tensor.shape[0], latent_dim, 1, 1), device=device, dtype=th.float, generator=generator)

    def generate_once():
        return model(z, conditions_tensor)

    metadata = {
        "latent_dim": latent_dim,
        "generator_output_activation": run_config.get("generator_output_activation", "tanh"),
    }
    return generate_once, metadata


def load_diffusion_generation_fn(
    *,
    checkpoint_path: Path,
    problem: Any,
    conditions_tensor: th.Tensor,
    device: th.device,
    seed: int,
) -> tuple[Callable[[], th.Tensor], dict[str, Any]]:
    """Load diffusion and return a callable that performs one batched sample."""
    checkpoint = th.load(str(checkpoint_path), map_location=device)
    run_config: dict[str, Any] = dict(checkpoint.get("args", {}))
    model_config: dict[str, Any] = dict(checkpoint.get("model_config", {}))
    num_timesteps = int(model_config.get("num_timesteps", run_config["num_timesteps"]))
    noise_schedule = model_config.get("noise_schedule", run_config["noise_schedule"])
    layers_per_block = int(model_config.get("layers_per_block", run_config["layers_per_block"]))

    model = UNet2DConditionModel(
        sample_size=problem.design_space.shape,
        in_channels=1,
        out_channels=1,
        cross_attention_dim=64,
        block_out_channels=(32, 64, 128, 256),
        down_block_types=("CrossAttnDownBlock2D", "CrossAttnDownBlock2D", "CrossAttnDownBlock2D", "DownBlock2D"),
        up_block_types=("UpBlock2D", "CrossAttnUpBlock2D", "CrossAttnUpBlock2D", "CrossAttnUpBlock2D"),
        layers_per_block=layers_per_block,
        transformer_layers_per_block=1,
        encoder_hid_dim=len(problem.conditions_keys),
        only_cross_attention=True,
    ).to(device)
    model.load_state_dict(checkpoint["model"])
    model.eval()

    betas = beta_schedule(
        t=num_timesteps,
        start=1e-4,
        end=0.02,
        scale=1.0,
        options={
            "cosine": noise_schedule == "cosine",
            "exp_biasing": noise_schedule == "exp",
            "exp_bias_factor": 1,
        },
    )
    sampler = DiffusionSampler(num_timesteps, betas)
    design_shape = problem.design_space.shape
    n_gen = conditions_tensor.shape[0]

    def generate_once():
        designs = th.randn((n_gen, 1, *design_shape), device=device)
        for i in reversed(range(num_timesteps)):
            t = th.full((n_gen,), i, device=device, dtype=th.long)
            designs = sampler.sample_timestep(model, designs, t, conditions_tensor)
        return designs

    metadata = {
        "num_timesteps": num_timesteps,
        "noise_schedule": noise_schedule,
        "layers_per_block": layers_per_block,
    }
    return generate_once, metadata


def load_flow_generation_fn(
    *,
    checkpoint_path: Path,
    problem: Any,
    conditions_tensor: th.Tensor,
    device: th.device,
    args: Args,
) -> tuple[Callable[[], th.Tensor], dict[str, Any]]:
    """Load flow matching and return a callable that performs one batched sample."""
    from engiopt.flow_matching_2d_cond.core import build_model as build_flow_matching_model
    from engiopt.flow_matching_2d_cond.core import generate_samples
    from engiopt.flow_matching_2d_cond.core import load_local_checkpoint
    from engiopt.flow_matching_2d_cond.evaluate_flow_matching_2d_cond import checkpoint_config

    checkpoint = load_local_checkpoint(str(checkpoint_path), device)
    run_config: dict[str, Any] = dict(checkpoint.get("args", {}))
    layers_per_block = int(checkpoint_config(checkpoint, "layers_per_block", run_config.get("layers_per_block", 2)))
    num_train_timesteps = int(
        checkpoint_config(checkpoint, "num_train_timesteps", run_config.get("num_train_timesteps", 1000))
    )
    integration_steps = args.flow_integration_steps
    if integration_steps is None:
        integration_steps = int(checkpoint_config(checkpoint, "integration_steps", run_config.get("integration_steps", 50)))

    model = build_flow_matching_model(
        design_shape=problem.design_space.shape,
        encoder_hid_dim=len(problem.conditions_keys),
        layers_per_block=layers_per_block,
    ).to(device)
    model.load_state_dict(checkpoint["model"])
    model.eval()

    def generate_once():
        return generate_samples(
            model=model,
            design_shape=problem.design_space.shape,
            encoder_hidden_states=conditions_tensor,
            integration_steps=integration_steps,
            num_train_timesteps=num_train_timesteps,
            device=device,
            method=args.flow_method,
            atol=args.atol,
            rtol=args.rtol,
        )

    metadata = {
        "integration_steps": integration_steps,
        "num_train_timesteps": num_train_timesteps,
        "layers_per_block": layers_per_block,
        "flow_method": args.flow_method,
    }
    return generate_once, metadata


def write_csv_row(path: Path, row: dict[str, Any], *, append: bool) -> None:
    """Write one benchmark row with deterministic field ordering."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = list(row.keys())
    mode = "a" if append and path.exists() else "w"
    with path.open(mode, newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        if mode == "w":
            writer.writeheader()
        writer.writerow(row)


if __name__ == "__main__":
    args = tyro.cli(Args)
    if args.n_samples <= 0:
        raise ValueError("--n-samples must be positive")

    device = select_device(args.device)
    th.manual_seed(args.seed)
    if device.type == "cuda":
        th.backends.cudnn.benchmark = True

    problem = BUILTIN_PROBLEMS[args.problem_id]()
    problem.reset(seed=args.seed)
    conditions_tensor, _, _, sampled_indices = sample_conditions(
        problem=problem,
        n_samples=args.n_samples,
        device=device,
        seed=args.seed,
    )
    if args.model_id in {"flow_matching_2d_cond", "diffusion_2d_cond"}:
        conditions_tensor = conditions_tensor.unsqueeze(1)
    else:
        conditions_tensor = conditions_tensor.unsqueeze(-1).unsqueeze(-1)

    checkpoint_path, checkpoint_source, selected_epoch, selected_metric = resolve_checkpoint(args)
    if args.model_id == "cgan_cnn_2d":
        generate_once, model_metadata = load_cgan_generation_fn(
            checkpoint_path=checkpoint_path,
            problem=problem,
            conditions_tensor=conditions_tensor,
            device=device,
            seed=args.seed,
        )
    elif args.model_id == "diffusion_2d_cond":
        generate_once, model_metadata = load_diffusion_generation_fn(
            checkpoint_path=checkpoint_path,
            problem=problem,
            conditions_tensor=conditions_tensor,
            device=device,
            seed=args.seed,
        )
    else:
        generate_once, model_metadata = load_flow_generation_fn(
            checkpoint_path=checkpoint_path,
            problem=problem,
            conditions_tensor=conditions_tensor,
            device=device,
            args=args,
        )

    summary = benchmark_callable(
        generate_once,
        device=device,
        warmup_repeats=args.warmup_repeats,
        timed_repeats=args.timed_repeats,
    )

    row: dict[str, Any] = {
        "model_id": args.model_id,
        "problem_id": args.problem_id,
        "seed": args.seed,
        "n_samples": args.n_samples,
        "generation_runtime_sec": f"{summary.mean_runtime_sec:.12g}",
        "generation_runtime_sec_mean": f"{summary.mean_runtime_sec:.12g}",
        "generation_runtime_sec_median": f"{summary.median_runtime_sec:.12g}",
        "generation_runtime_sec_std": f"{summary.std_runtime_sec:.12g}",
        "generation_runtime_sec_min": f"{summary.min_runtime_sec:.12g}",
        "generation_runtime_sec_max": f"{summary.max_runtime_sec:.12g}",
        "generation_samples_per_sec": f"{args.n_samples / summary.mean_runtime_sec:.12g}",
        "generation_samples_per_sec_median": f"{args.n_samples / summary.median_runtime_sec:.12g}",
        "generation_total_runtime_sec": f"{summary.total_runtime_sec:.12g}",
        "warmup_repeats": args.warmup_repeats,
        "timed_repeats": summary.timed_repeats,
        "timing_method": "warmup_repeated_wall_clock_cuda_synchronized",
        "device": str(device),
        "device_name": gpu_name(device),
        "torch_version": th.__version__,
        "checkpoint_path": str(checkpoint_path),
        "checkpoint_source": checkpoint_source,
        "selected_epoch": "" if selected_epoch is None else selected_epoch,
        "selected_validation_mmd": "" if selected_metric is None else f"{selected_metric:.12g}",
        "sampled_indices": ",".join(str(int(index)) for index in sampled_indices.tolist()),
        "hostname": platform.node(),
        "slurm_job_id": os.environ.get("SLURM_JOB_ID", ""),
        "slurm_array_task_id": os.environ.get("SLURM_ARRAY_TASK_ID", ""),
    }
    row.update(model_metadata)

    out_path = Path(
        args.output_csv.format(model_id=args.model_id, problem_id=args.problem_id, seed=args.seed)
    )
    write_csv_row(out_path, row, append=args.append_output)
    print(
        f"Wrote generation benchmark to {out_path} "
        f"(mean={summary.mean_runtime_sec:.6g}s, median={summary.median_runtime_sec:.6g}s, "
        f"samples/sec={args.n_samples / summary.mean_runtime_sec:.6g})"
    )
